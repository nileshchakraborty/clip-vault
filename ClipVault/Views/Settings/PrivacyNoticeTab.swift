import SwiftUI

public struct PrivacyNoticeTab: View {
    public var body: some View {
        ScrollView {
            VStack(alignment: .leading, spacing: 16) {
                HStack(spacing: 8) {
                    Image(systemName: "lock.shield.fill")
                        .font(.system(size: 20))
                        .foregroundColor(.green)

                    Text("Privacy Notice")
                        .font(.system(size: 15, weight: .bold))
                }

                VStack(alignment: .leading, spacing: 12) {
                    privacySection(
                        title: "1. Zero Telemetry & Zero Cloud Sync",
                        bodyText: "ClipVault makes NO network calls. There are no tracking analytics, crash beacons, usage telemetry, or third-party SDKs bundled with this software. Your clipboard contents never leave your machine."
                    )

                    Divider()

                    privacySection(
                        title: "2. Ephemeral In-Memory Model",
                        bodyText: "All copied items are retained strictly in volatile RAM memory up to your chosen limit (capped at 50). When you quit the app or restart your Mac, all history is instantly discarded. No database, logs, or unencrypted text files are retained on your disk."
                    )

                    Divider()

                    privacySection(
                        title: "3. Password Manager Shielding",
                        bodyText: "ClipVault automatically checks macOS pasteboard types for concealment flags used by industry-standard password managers (such as 1Password, Bitwarden, KeePassXC, and Apple Keychain). Items flagged with ConcealedType or AutoGeneratedType are immediately ignored and never captured into history."
                    )

                    Divider()

                    privacySection(
                        title: "4. Optional Pinned Items Persistence",
                        bodyText: "If you explicitly opt-in to 'Persist Pinned items across app restarts' in Settings, only your pinned items are saved to your user Application Support directory. If this toggle is disabled, even pinned items are wiped on app restart."
                    )
                }
                .padding()
                .background(Color(NSColor.controlBackgroundColor))
                .cornerRadius(10)

                HStack {
                    Image(systemName: "checkmark.seal.fill")
                        .foregroundColor(.green)
                    Text("100% Offline • Transparent • Privacy-Guaranteed")
                        .font(.system(size: 11, weight: .medium))
                        .foregroundColor(.secondary)
                }
                .frame(maxWidth: .infinity, alignment: .center)
                .padding(.top, 4)
            }
            .padding(16)
        }
    }

    private func privacySection(title: String, bodyText: String) -> some View {
        VStack(alignment: .leading, spacing: 4) {
            Text(title)
                .font(.system(size: 12, weight: .semibold))
                .foregroundColor(.primary)

            Text(bodyText)
                .font(.system(size: 11))
                .foregroundColor(.secondary)
                .lineSpacing(2)
        }
    }
}
