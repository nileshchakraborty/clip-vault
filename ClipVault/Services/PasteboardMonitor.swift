import AppKit
import Foundation
import ImageIO

public final class PasteboardMonitor {
    private var timer: Timer?
    private var lastChangeCount: Int
    private var internalCopyCount: Int = -1
    private let pasteboard = NSPasteboard.general

    // Adaptive idle state tracking
    private var secondsSinceLastChange: TimeInterval = 0
    private var currentInterval: TimeInterval = 0.5

    public var onItemDetected: ((ClipboardItem) -> Void)?

    // Memory guards
    public static let maxTextCharacters: Int = 50_000
    public static let maxRegexCheckLength: Int = 2_048
    public static let maxIngestibleImageBytes: Int = 60 * 1024 * 1024 // Accept up to 60MB raw images
    public static let maxStoredImageBytes: Int = 800 * 1024 // Compact images > 800KB down to high-res JPEG

    // Concealed types from Password Managers and OS security
    private static let concealedTypeIdentifiers: [String] = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.AutoGeneratedType",
        "org.nspasteboard.TransientType",
        "com.agilebits.onepassword",
        "de.plessman.PwsSafe",
        "com.bitwarden"
    ]

    public init() {
        self.lastChangeCount = pasteboard.changeCount
    }

    public func startMonitoring() {
        scheduleTimer(interval: 0.5, tolerance: 0.15)
    }

    public func stopMonitoring() {
        timer?.invalidate()
        timer = nil
    }

    public func resetToActivePolling() {
        secondsSinceLastChange = 0
        if currentInterval != 0.5 {
            scheduleTimer(interval: 0.5, tolerance: 0.15)
        }
    }

    private func scheduleTimer(interval: TimeInterval, tolerance: TimeInterval) {
        timer?.invalidate()
        currentInterval = interval

        let t = Timer(timeInterval: interval, repeats: true) { [weak self] _ in
            self?.checkForChanges()
        }
        t.tolerance = tolerance
        RunLoop.main.add(t, forMode: .common)
        self.timer = t
    }

    public func notifyInternalCopy() {
        self.internalCopyCount = pasteboard.changeCount
        resetToActivePolling()
    }

    private func checkForChanges() {
        autoreleasepool {
            let currentCount = pasteboard.changeCount
            if currentCount != lastChangeCount {
                lastChangeCount = currentCount
                resetToActivePolling()

                if currentCount == internalCopyCount {
                    return
                }

                if isConcealed() {
                    return
                }

                if let item = extractClipboardItem() {
                    onItemDetected?(item)
                }
            } else {
                // Adaptive idle backoff calculation
                secondsSinceLastChange += currentInterval

                if secondsSinceLastChange >= 300 && currentInterval < 3.5 {
                    // Deep idle after 5 minutes: poll every 3.5 seconds
                    scheduleTimer(interval: 3.5, tolerance: 1.0)
                } else if secondsSinceLastChange >= 30 && currentInterval < 1.5 {
                    // Idle after 30 seconds: poll every 1.5 seconds
                    scheduleTimer(interval: 1.5, tolerance: 0.5)
                }
            }
        }
    }

    private func isConcealed() -> Bool {
        guard let types = pasteboard.types else { return false }
        for type in types {
            let identifier = type.rawValue
            if PasteboardMonitor.concealedTypeIdentifiers.contains(identifier) {
                return true
            }
        }
        return false
    }

    private func extractClipboardItem() -> ClipboardItem? {
        // 1. Check for Image (TIFF / PNG)
        if let types = pasteboard.types,
           types.contains(.tiff) || types.contains(.png) {
            if let imgData = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff) {
                // Safeguard: Accept images up to 60MB from the web
                if imgData.count <= PasteboardMonitor.maxIngestibleImageBytes {
                    let thumbData = generateMicroThumbnail(from: imgData, maxPixelDimension: 96)
                    let safeData = compressOversizedImage(from: imgData, maxDimension: 1920) ?? imgData
                    let content = ClipboardContent.image(data: safeData, thumbnailData: thumbData)
                    return ClipboardItem(content: content)
                }
            }
        }

        // 2. Check for Plain Text / String
        if let rawString = pasteboard.string(forType: .string) {
            let trimmed = rawString.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !trimmed.isEmpty else { return nil }

            let isTruncated = trimmed.count > PasteboardMonitor.maxTextCharacters
            let safeString = isTruncated
                ? String(trimmed.prefix(PasteboardMonitor.maxTextCharacters))
                : trimmed

            // Fast-path: Only check regex if string is short enough (< 2048 characters)
            if trimmed.count <= PasteboardMonitor.maxRegexCheckLength {
                if let hexColor = parseHexColor(trimmed) {
                    let content = ClipboardContent.color(hex: hexColor)
                    return ClipboardItem(content: content)
                }

                if let url = parseURL(trimmed) {
                    let content = ClipboardContent.url(url)
                    return ClipboardItem(content: content)
                }
            }

            // Check for Rich Text (RTF)
            if let rtfData = pasteboard.data(forType: .rtf) {
                let safeRTFData = rtfData.count <= 1_000_000 ? rtfData : nil
                let content = ClipboardContent.richText(
                    data: safeRTFData ?? Data(),
                    plainString: safeString,
                    isTruncated: isTruncated
                )
                return ClipboardItem(content: content)
            }

            // Standard Plain Text
            let content = ClipboardContent.text(safeString, isTruncated: isTruncated)
            return ClipboardItem(content: content)
        }

        return nil
    }

    private func generateMicroThumbnail(from data: Data, maxPixelDimension: Int) -> Data? {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil) else { return nil }
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceShouldCacheImmediately: true,
            kCGImageSourceThumbnailMaxPixelSize: maxPixelDimension
        ]
        guard let cgThumb = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary) else { return nil }
        let bitmapRep = NSBitmapImageRep(cgImage: cgThumb)
        return bitmapRep.representation(using: .jpeg, properties: [.compressionFactor: 0.7])
    }

    private func compressOversizedImage(from data: Data, maxDimension: Int) -> Data? {
        guard data.count > PasteboardMonitor.maxStoredImageBytes else { return data }
        guard let source = CGImageSourceCreateWithData(data as CFData, nil) else { return nil }
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceShouldCacheImmediately: true,
            kCGImageSourceThumbnailMaxPixelSize: maxDimension
        ]
        guard let cgImage = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary) else { return nil }
        let bitmapRep = NSBitmapImageRep(cgImage: cgImage)
        return bitmapRep.representation(using: .jpeg, properties: [.compressionFactor: 0.85])
    }

    private func parseHexColor(_ text: String) -> String? {
        let pattern = "^#?([A-Fa-f0-9]{6}|[A-Fa-f0-9]{3}|[A-Fa-f0-9]{8})$"
        guard text.range(of: pattern, options: .regularExpression) != nil else { return nil }
        return text.hasPrefix("#") ? text : "#\(text)"
    }

    private func parseURL(_ text: String) -> URL? {
        guard (text.hasPrefix("http://") || text.hasPrefix("https://") || text.hasPrefix("file://")),
              let url = URL(string: text),
              url.host != nil || text.hasPrefix("file://") else {
            return nil
        }
        return url
    }
}
